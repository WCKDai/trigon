"""Original adapter using Blender's public Python API, run as a separate program.

Geometry is generated by Trigon's Rust model and supplied as an embedded GLB. This script
only converts the rendering exchange format, then checks a fresh FBX import. It imports
no Blender implementation modules or add-on source. No GUI or GPU rendering is started.
"""

import argparse
from collections import Counter, defaultdict
import json
import math
from pathlib import Path
import shutil
import sys
import tempfile

import bpy
from mathutils import Vector
from mathutils.kdtree import KDTree


def geometry():
    vertices = defaultdict(list)
    ids = Counter()
    triangles = 0
    uv_objects = 0
    textured = set()
    texture_images = set()
    for obj in bpy.context.scene.objects:
        if obj.type != "MESH":
            continue
        identity = obj.get("trigon_id")
        if not isinstance(identity, str) or not identity:
            raise ValueError("missing Trigon source identity")
        ids[identity] += 1
        points=[tuple(obj.matrix_world @ v.co) for v in obj.data.vertices]
        if any(not math.isfinite(v) for p in points for v in p):
            raise ValueError("nonfinite rendering geometry")
        vertices[identity].extend(points)
        obj.data.calc_loop_triangles()
        triangles += len(obj.data.loop_triangles)
        uv_objects += bool(obj.data.uv_layers)
        for slot in obj.material_slots:
            mat = slot.material
            if mat and mat.node_tree:
                for node in mat.node_tree.nodes:
                    if node.type == "TEX_IMAGE" and node.image:
                        if len(node.image.pixels) < 4 or min(node.image.size) <= 0:
                            raise ValueError("missing texture pixels")
                        texture_images.add(node.image.name)
                        textured.add(mat.name)
    if not vertices:
        raise ValueError("no model meshes")
    return vertices, ids, triangles, uv_objects, textured, texture_images


def distance(a, b):
    """Maximum two-way nearest-vertex distance, retaining each semantic element's identity."""
    tree = KDTree(len(b))
    for i, point in enumerate(b):
        tree.insert(Vector(point), i)
    tree.balance()
    return max((tree.find(Vector(point))[2] for point in a), default=0.0)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--report", required=True)
    args = parser.parse_args(sys.argv[sys.argv.index("--") + 1 :])
    source = Path(args.input).resolve()
    output = Path(args.output).resolve()
    report = Path(args.report).resolve()
    if source.suffix != ".glb" or output.suffix != ".fbx":
        raise ValueError("expected GLB input and FBX output")
    bpy.ops.wm.read_factory_settings(use_empty=True)
    bpy.ops.import_scene.gltf(filepath=str(source))
    scene = bpy.context.scene
    scene.unit_settings.system = "METRIC"
    scene.unit_settings.scale_length = 1.0
    before, ids, triangles, uv_objects, textured, texture_images = geometry()
    renamed=sum(obj.type=="MESH" and obj.name!=obj.get("trigon_id") for obj in scene.objects)
    # Packed GLB images must be included in the FBX, not linked back to a temp directory.
    for image in bpy.data.images:
        if image.source == "FILE" and not image.packed_file:
            image.pack()
    bpy.ops.export_scene.fbx(
        filepath=str(output),
        check_existing=False,
        object_types={"MESH"},
        global_scale=1.0,
        apply_unit_scale=True,
        apply_scale_options="FBX_SCALE_UNITS",
        axis_forward="-Z",
        axis_up="Y",
        use_custom_props=True,
        use_triangles=True,
        mesh_smooth_type="OFF",
        bake_anim=False,
        path_mode="COPY",
        embed_textures=True,
    )
    bpy.ops.wm.read_factory_settings(use_empty=True)
    with tempfile.TemporaryDirectory(prefix="trigon-fbx-verify-",dir=output.parent) as directory:
        fresh=Path(directory)
        portable=fresh/"portable.fbx"
        shutil.copyfile(output,portable)
        bpy.ops.import_scene.fbx(filepath=str(portable), use_custom_props=True,use_image_search=False)
        after, got_ids, got_triangles, got_uv, got_textured, got_images = geometry()
        if ids != got_ids or triangles != got_triangles:
            raise ValueError("FBX round-trip changed source identities or triangle inventory")
        if got_uv < uv_objects or len(got_textured) < len(textured) or len(got_images)<len(texture_images):
            raise ValueError("FBX round-trip lost UVs or textured materials")
        for image in bpy.data.images:
            if image.name in got_images and not image.packed_file and not Path(bpy.path.abspath(image.filepath)).resolve().is_relative_to(fresh):
                raise ValueError("FBX texture still depends on a file outside its fresh import folder")
    worst = max(max(distance(before[key], after[key]), distance(after[key], before[key])) for key in before)
    if worst > 0.0001:
        raise ValueError("FBX round-trip changed model vertices beyond 0.1 mm")
    report.write_text(json.dumps({
        "blender": bpy.app.version_string,
        "mesh_objects": sum(ids.values()),
        "triangles": triangles,
        "source_ids_preserved": True,
        "object_names_differing_from_source_ids":renamed,
        "max_source_id_bytes":max(len(key.encode("utf-8")) for key in ids),
        "max_vertex_deviation_mm": worst * 1000.0,
        "uv_objects": got_uv,
        "textured_materials": len(got_textured),
        "texture_images": len(got_images),
        "embedded_textures": True,
        "units": "metres, with FBX unit and axis metadata",
        "lumion_import_verified": False,
    }, indent=2))


if __name__ == "__main__":
    main()
